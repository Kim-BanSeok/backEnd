    '사진에서 아래 항목의 값만 뽑아 JSON 객체 하나로만 답해. 설명이나 다른 글자는 쓰지 마.',
    '',
    '항목:',
    lines,
    '',
    '규칙:',
    '- 키는 위 항목 이름 그대로, 값은 위에 적힌 형식 그대로 써.',
    '- 사진만으로 확실하지 않으면 null 로 답해. 추측해서 채우지 마.',
    '- 가로, 세로, 가격은 사진으로 재지 마. 항목에 넣지 마.',
