export const FACTORY_CATEGORY_CODES = FACTORY_CATEGORIES.map((category) => category.code);

const NORMALIZED = FACTORY_CATEGORIES.map((category) => ({
  code: category.code,
  keywords: category.keywords.map((word) => word.replace(/[^\p{L}\p{N}]+/gu, '').toLowerCase()),
}));

export function classifyIndustry(industry) {
  const text = String(industry ?? '').replace(/[^\p{L}\p{N}]+/gu, '').toLowerCase();
  if (!text) return 'OTHER';
  for (const category of NORMALIZED) {
    if (category.code === 'OTHER') continue;
    if (category.keywords.some((word) => text.includes(word))) return category.code;
  }
  return 'OTHER';
}
